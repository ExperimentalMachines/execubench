"""execubench command line.

python -m execubench models scan                 # pin every XNNPACK .pte on the Hub
python -m execubench devicefarm probe <pool-arn>  # run the device probe on a pool
python -m execubench devicefarm pull <run-arn> <dest>
python -m execubench devices build <probe-dir>   # parse dumps, write devices.json
python -m execubench validate                    # check generated files against schemas/
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _models_scan(args) -> int:
    from . import models

    inv = models.scan()
    out = {
        "scanned_utc": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "note": "Generated by execubench models scan; do not edit by hand.",
        "files": inv,
    }
    Path(args.out).write_text(json.dumps(out, indent=1) + "\n")
    bad = [f for f in inv if not f["hashes_agree"]]
    print(f"{len(inv)} files, {len({f['repo'] for f in inv})} repos, {len(bad)} hash disagreements")
    return 1 if bad else 0


def _devicefarm_pull(args) -> int:
    from . import devicefarm, devices

    names = devices.kernel_part_names()
    for folder in devicefarm.pull_run(devicefarm.client(), args.run_arn, Path(args.dest)):
        probe = folder / "artifacts" / "probe"
        if probe.exists():
            (folder / "profile.json").write_text(json.dumps(devices.profile(probe, names), indent=1) + "\n")
        print(folder)
    return 0


def _devicefarm_probe(args) -> int:
    import tempfile
    import zipfile

    from . import devicefarm

    df = devicefarm.client()
    here = ROOT / "devicefarm" / "probe"
    with tempfile.TemporaryDirectory() as tmp:
        pkg = Path(tmp) / "probe_pkg.zip"
        with zipfile.ZipFile(pkg, "w") as z:
            z.writestr("requirements.txt", "pytest\n")
            z.write(here / "probe.sh", "tests/probe.sh")
            z.writestr("tests/test_probe.py", "def test_placeholder():\n    assert True\n")
        app = devicefarm.upload(df, args.project_arn, Path(args.carrier_apk), "ANDROID_APP")
        test = devicefarm.upload(df, args.project_arn, pkg, "APPIUM_PYTHON_TEST_PACKAGE")
        spec = devicefarm.upload(df, args.project_arn, here / "testspec.yml", "APPIUM_PYTHON_TEST_SPEC")
    run = df.schedule_run(
        projectArn=args.project_arn,
        appArn=app,
        devicePoolArn=args.pool_arn,
        name=args.name,
        test={"type": "APPIUM_PYTHON", "testPackageArn": test, "testSpecArn": spec},
        # Screen recording competes for CPU and GPU on the phone; the probe and every
        # benchmark run without it.
        executionConfiguration={"jobTimeoutMinutes": 15, "videoCapture": False},
    )["run"]
    print(run["arn"])
    return 0


def _devices_build(args) -> int:
    from . import registry

    roots = [Path(d) for d in args.probe_dirs]
    recs = registry.build(roots)
    out = {"generated_from": [str(r) for r in roots] + ["data/devices/specs.yaml"], "devices": recs}
    Path(args.out).write_text(json.dumps(out, indent=1) + "\n")
    print(f"{len(recs)} device records -> {args.out}")
    return 0


def _datasets_stats(args) -> int:
    from . import datasets

    out = datasets.stats()
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(out, indent=1) + "\n")
    print(f"{len(out)} datasets -> {args.out}")
    return 0


def _budget(args) -> int:
    from . import budget

    print(json.dumps(budget.budget(), indent=1))
    return 0


def _devices_table(args) -> int:
    from . import registry

    recs = json.loads(Path(args.devices).read_text())["devices"]
    doc = Path(args.doc)
    text = doc.read_text()
    start, end = text.index(registry.TABLE_BEGIN), text.index(registry.TABLE_END)
    table = registry.markdown_table(recs)
    doc.write_text(text[: start + len(registry.TABLE_BEGIN)] + "\n\n" + table + "\n" + text[end:])
    print(f"{sum(r.get('latest_for_model', True) for r in recs)} rows -> {doc}")
    return 0


def _validate(args) -> int:
    from . import schemas

    errors = schemas.validate_repo()
    for e in errors:
        print(e)
    print("ok" if not errors else f"{len(errors)} errors")
    return 1 if errors else 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="execubench")
    sub = p.add_subparsers(dest="cmd", required=True)

    m = sub.add_parser("models").add_subparsers(dest="sub", required=True)
    s = m.add_parser("scan")
    s.add_argument("--out", default=str(ROOT / "data" / "models" / "xnnpack.json"))
    s.set_defaults(fn=_models_scan)

    d = sub.add_parser("devicefarm").add_subparsers(dest="sub", required=True)
    s = d.add_parser("pull")
    s.add_argument("run_arn")
    s.add_argument("dest")
    s.set_defaults(fn=_devicefarm_pull)
    s = d.add_parser("probe")
    s.add_argument("project_arn")
    s.add_argument("pool_arn")
    s.add_argument("--carrier-apk", required=True, help="Any installable APK; the probe ignores it")
    s.add_argument("--name", default=f"probe-{datetime.now(UTC):%Y-%m-%d}")
    s.set_defaults(fn=_devicefarm_probe)

    v = sub.add_parser("devices").add_subparsers(dest="sub", required=True)
    s = v.add_parser("build")
    s.add_argument("probe_dirs", nargs="+", help="Probe run folders, oldest first; later runs win per device")
    s.add_argument("--out", default=str(ROOT / "data" / "devices" / "devices.json"))
    s.set_defaults(fn=_devices_build)

    t = sub.add_parser("datasets").add_subparsers(dest="sub", required=True)
    s = t.add_parser("stats")
    s.add_argument("--out", default=str(ROOT / "data" / "datasets" / "stats.json"))
    s.set_defaults(fn=_datasets_stats)

    s = sub.add_parser("budget")
    s.set_defaults(fn=_budget)

    s = v.add_parser("table")
    s.add_argument("--devices", default=str(ROOT / "data" / "devices" / "devices.json"))
    s.add_argument("--doc", default=str(ROOT / "docs" / "DEVICES.md"))
    s.set_defaults(fn=_devices_table)

    s = sub.add_parser("validate")
    s.set_defaults(fn=_validate)

    args = p.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
